const categories = ['All questions', ...new Set(faqs.map((item) => item.category))];

export function FaqPage() {
    const [category, setCategory] = useState('All questions');
    const [query, setQuery] = useState('');
    const filtered = useMemo(
        () =>
            faqs.filter(
                (item) =>
                    (category === 'All questions' || item.category === category) &&
                    `${item.question} ${item.answer}`
                        .toLowerCase()
                        .includes(query.toLowerCase().trim())
            ),
        [category, query]
    );
    return (
        <>
            <PageHero eyebrow="FAQ" title="Good questions deserve clear answers.">
                Find practical answers about setup, appointments, queues, no-show assistance and
                access.
            </PageHero>
            <section className="m-section m-faq">
                <div className="m-container">
                    <label className="m-faq-search">
                        Search questions
                        <input
                            type="search"
                            value={query}
                            onChange={(event) => setQuery(event.target.value)}
                            placeholder="Try “queue” or “staff access”"
                        />
                    </label>
                    <div className="m-faq-categories" aria-label="FAQ categories">
                        {categories.map((item) => (
                            <button
                                key={item}
                                type="button"
                                aria-pressed={category === item}
                                onClick={() => setCategory(item)}
                            >
                                {item}
                            </button>
                        ))}
                    </div>
                    <div className="m-faq-results">
                        <p>
                            {filtered.length} {filtered.length === 1 ? 'answer' : 'answers'} found
                        </p>
                        {filtered.length ? (
                            filtered.map((item) => (
                                <details key={item.question}>
                                    <summary>
                                        <span>{item.question}</span>
                                        <span aria-hidden="true">+</span>
                                    </summary>
                                    <div>
                                        <p>{item.answer}</p>
                                        {item.href && (
                                            <ArrowLink to={item.href}>{item.link}</ArrowLink>
                                        )}
                                    </div>
                                </details>
                            ))
                        ) : (
                            <div className="m-faq-empty">
                                No questions match this search. Try another term or{' '}
                                <Link to="/contact">contact the team</Link>.
                            </div>
                        )}
                    </div>
                </div>
            </section>
            <EndCta
                title="Still have a question?"
                copy="Tell us what you would like to understand about Pravaah."
            />
        </>
    );
}

